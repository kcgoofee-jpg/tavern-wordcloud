/** Chinese is returned as-is; the key is the text. */
const TABLES: Record<Lang, Record<string, string>> = { zh: {}, en: EN };

export const LANG_LABEL: Record<Lang, string> = { zh: '中文', en: 'English' };

/** Follows the browser: Chinese for zh, English otherwise. */
export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'zh';
  return /^zh\b/i.test(navigator.language ?? '') ? 'zh' : 'en';
}

/**
 * Translate. Unknown keys return the Chinese text. Placeholders use `{name}`;
 * the key must be a string literal so the i18n test can find it.
 */
export function translate(lang: Lang, zh: string, vars?: Record<string, string | number>): string {
  return fill(TABLES[lang][zh] ?? zh, vars);
}

/** Keys of the English table, for tests. */
export function englishKeys(): string[] {
  return Object.keys(EN);
}

/**
 * Language seen by non-hook code (dynamic values from core / worker / server).
 * Initialised from the browser like the default setting; useSettings syncs it.
 */
let currentLang: Lang = detectLang();
export function setCurrentLang(lang: Lang): void {
  currentLang = lang;
}

/**
 * Translate a dynamic value (worker progress, parse warnings, theme labels…).
 * Not scanned for literals; unknown text is returned unchanged.
 */
export function tx(value: string): string {
  return TABLES[currentLang][value] ?? value;
}

/**
 * Resolve a UserText. Template keys go through the dictionary with their
 * params; string params that are themselves zh()-marked (e.g. an upstream error
 * embedded in a note) are translated too. A `src` prefix stays verbatim.
 */
export function txv(value: UserText): string {
  if (typeof value === 'string') return tx(value);
  const resolve = (v: TplParam): string | number =>
    typeof v === 'object' ? txv(v) : typeof v === 'string' ? tx(v) : v;
  const params = value.params && Object.fromEntries(
    Object.entries(value.params).map(([k, v]) => [k, resolve(v)]),
  );
  const s = translate(currentLang, value.key, params);
  return value.src ? value.src + (currentLang === 'zh' ? '：' : ': ') + s : s;
}

/** Language is provided through context rather than passed down as a prop. */
export const LangContext = createContext<Lang>('zh');

/** Translation hook. Call as `t('中文原文')` with a literal argument. */
export function useT(): (zh: string, vars?: Record<string, string | number>) => string {
  const lang = useContext(LangContext);
  return (zh: string, vars?: Record<string, string | number>) => translate(lang, zh, vars);
}
